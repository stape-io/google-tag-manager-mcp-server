import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

// Importing package.json would move it outside rootDir; Workers cannot read it
// at runtime. Keep generated source, and check it before CI builds can repair it.
const check = process.argv.includes("--check");
const root = fileURLToPath(new URL("../", import.meta.url));
const packageDirs = process.argv.includes("--all")
  ? ["packages/core", "packages/cli", "apps/worker"].map((dir) =>
      path.join(root, dir),
    )
  : [process.cwd()];
for (const packageDir of packageDirs) {
  const target = path.join(packageDir, "src", "version.ts");
  const { name, version } = JSON.parse(
    readFileSync(path.join(packageDir, "package.json"), "utf8"),
  );
  const contents = `// Generated by scripts/generate-version.mjs - do not edit.
export const PACKAGE_NAME = "${name}";

export const PACKAGE_VERSION = "${version}";
`;
  let current;
  try {
    current = readFileSync(target, "utf8");
  } catch {
    current = null;
  }
  if (current === contents) continue;
  if (check) {
    console.error(
      `Generated version is stale: ${name}. Run node scripts/generate-version.mjs --all.`,
    );
    process.exitCode = 1;
  } else {
    writeFileSync(target, contents);
    console.log(`generate-version: ${name}@${version}`);
  }
}
